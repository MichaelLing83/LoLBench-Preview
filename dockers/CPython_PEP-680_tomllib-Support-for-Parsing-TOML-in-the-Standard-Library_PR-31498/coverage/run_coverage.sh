#!/usr/bin/env bash
# LoLBench coverage runner for CPython PR-31498 (PEP 680: tomllib).
#
# Applies solution.patch + eval_tests.patch on top of base_commit and
# measures F2P/P2P line coverage of the 4 new Lib/tomllib/*.py files
# using coverage.py.  We run F2P with coverage.py tracing, save the
# .coverage snapshot, clear, run P2P, save another snapshot, then ask
# coverage.py to emit per-file JSON and feed both snapshots to
# compute_coverage.py for the per-test cross-check + summary.
#
# Output:
#   /out/coverage_report.json   per-file + summary + tool_status
#
# Exit codes:
#   0 — all coverage tools succeeded; numbers are trustworthy.
#   2 — at least one tool failed; coverage_complete=false in the report.
#       Numbers are partial; do not use externally without a caveat.
#
# `set -e` so a failed `git apply`, `make`, or test runner aborts
# the script rather than silently proceeding into a partial run.
set -euo pipefail
PRIV=/opt/lolbench/private
CPYTHON=/workspace/cpython
PYTHON="$CPYTHON/python"
SUITE=${LOLBENCH_SUITE:-orig}

case "$SUITE" in
  orig|aug|union) ;;
  *) echo "[coverage] FATAL: unknown LOLBENCH_SUITE=$SUITE" >&2; exit 2 ;;
esac

HAS_AUG=0
if [ -f "$PRIV/eval_tests_aug.patch" ] \
   && [ -f "$PRIV/f2p_aug.txt" ] \
   && [ -f "$PRIV/p2p_aug.txt" ]; then
    HAS_AUG=1
fi
if [ "$SUITE" != "orig" ] && [ "$HAS_AUG" -eq 0 ]; then
    echo "[coverage] WARN: LOLBENCH_SUITE=$SUITE but no sidecar shipped; falling back to orig" >&2
    SUITE=orig
fi

cd "$CPYTHON"
git config --global --add safe.directory "$CPYTHON"
git reset --hard >/dev/null 2>&1
# Do NOT git clean -fdx — that wipes configure-generated files needed
# by `make`.  Every container is fresh (docker run --rm), so a tracked-
# file rewind is enough.

# Coverage measurement always applies BOTH patches.
git apply "$PRIV/solution.patch"
git apply "$PRIV/eval_tests.patch"
if [ "$SUITE" != "orig" ]; then
    git apply "$PRIV/eval_tests_aug.patch"
fi

COV_F2P_FILE=$PRIV/.coverage.f2p
COV_P2P_FILE=$PRIV/.coverage.p2p
COV_F2P_JSON=$PRIV/coverage_f2p.json
COV_P2P_JSON=$PRIV/coverage_p2p.json
rm -f "$COV_F2P_FILE" "$COV_P2P_FILE" "$COV_F2P_JSON" "$COV_P2P_JSON"

# ---- Reconfigure / rebuild if solution.patch touched configure or C ---
needs_reconfig=0
if grep -qE '^(diff --git a/(configure(\.ac)?|pyconfig\.h\.in|Makefile\.pre\.in)) ' "$PRIV/solution.patch"; then
    needs_reconfig=1
fi
if [ "$needs_reconfig" -eq 1 ]; then
    ./configure --prefix=/usr/local --enable-optimizations=no
fi
# stdlib_module_names.h is regenerated by make when the header changes.
jobs=$(awk '$1!="max"{printf("%d", ($1+$2-1)/$2)}' /sys/fs/cgroup/cpu.max 2>/dev/null)
: "${jobs:=$(nproc)}"
[ "$jobs" -lt 1 ] && jobs=1
make -j"$jobs" >/tmp/cov-rebuild.log 2>&1

# ---- Locate coverage.py target files ---------------------------------
# We measure only the 4 NEW solution.patch files (the Python/* C header
# is one line and not Python).
TOMLLIB_DIR="$CPYTHON/Lib/tomllib"
[ -d "$TOMLLIB_DIR" ] || { echo "ERROR: $TOMLLIB_DIR missing post-patch" >&2; exit 2; }

# Helper: run one unittest id under coverage.py, capture verdict.
# Writes  $1 = data_file   $2 = test_id ... → echoes "PASSED|FAILED|ERROR|SKIPPED"
run_one_with_coverage() {
    local data_file=$1; shift
    local tid=$1; shift
    local out
    set +e
    out=$( COVERAGE_FILE="$data_file" \
        "$PYTHON" -m coverage run --append \
                --source="$TOMLLIB_DIR" \
                --branch \
                -m unittest -v "$tid" 2>&1 )
    local rc=$?
    set -e
    # unittest summary line on stderr; coverage.py just appends to the
    # data file. Parse outcome via rc + stderr text.
    if echo "$out" | grep -qE "^(OK|ok)$"; then
        echo "PASSED"
    elif echo "$out" | grep -qE "^(FAILED|FAIL:)" ; then
        if echo "$out" | grep -q "ERRORS"; then echo "ERROR"; else echo "FAILED"; fi
    elif [ "$rc" -ne 0 ]; then
        # unittest non-zero rc means failure or error
        echo "ERROR"
    else
        echo "PASSED"
    fi
}

# ---- Run F2P under coverage ------------------------------------------
mapfile -t FAIL_TO_PASS_ORIG < <(grep -v '^\s*$' "$PRIV/f2p.txt")
mapfile -t PASS_TO_PASS_ORIG < <(grep -v '^\s*$' "$PRIV/p2p.txt")
FAIL_TO_PASS_AUG=()
PASS_TO_PASS_AUG=()
if [ "$HAS_AUG" -eq 1 ]; then
    mapfile -t FAIL_TO_PASS_AUG < <(grep -v '^\s*$' "$PRIV/f2p_aug.txt")
    mapfile -t PASS_TO_PASS_AUG < <(grep -v '^\s*$' "$PRIV/p2p_aug.txt")
fi

case "$SUITE" in
  orig)
    FAIL_TO_PASS=("${FAIL_TO_PASS_ORIG[@]}")
    PASS_TO_PASS=("${PASS_TO_PASS_ORIG[@]}")
    ;;
  aug)
    FAIL_TO_PASS=("${FAIL_TO_PASS_AUG[@]}")
    PASS_TO_PASS=("${PASS_TO_PASS_AUG[@]}")
    ;;
  union)
    FAIL_TO_PASS=("${FAIL_TO_PASS_ORIG[@]}" "${FAIL_TO_PASS_AUG[@]}")
    PASS_TO_PASS=("${PASS_TO_PASS_ORIG[@]}" "${PASS_TO_PASS_AUG[@]}")
    ;;
esac

F2P_EFFECTIVE=$PRIV/f2p_effective.txt
P2P_EFFECTIVE=$PRIV/p2p_effective.txt
printf '%s\n' "${FAIL_TO_PASS[@]}" > "$F2P_EFFECTIVE"
printf '%s\n' "${PASS_TO_PASS[@]}" > "$P2P_EFFECTIVE"

F2P_OK=true
F2P_VERDICTS=$PRIV/.f2p_verdicts.txt
: > "$F2P_VERDICTS"
while IFS= read -r tid; do
    [ -z "$tid" ] && continue
    v=$(run_one_with_coverage "$COV_F2P_FILE" "$tid" || echo ERROR)
    echo "$tid $v" >> "$F2P_VERDICTS"
done < "$F2P_EFFECTIVE"

# ---- Run P2P under coverage ------------------------------------------
P2P_OK=true
P2P_VERDICTS=$PRIV/.p2p_verdicts.txt
: > "$P2P_VERDICTS"
while IFS= read -r tid; do
    [ -z "$tid" ] && continue
    v=$(run_one_with_coverage "$COV_P2P_FILE" "$tid" || echo ERROR)
    echo "$tid $v" >> "$P2P_VERDICTS"
done < "$P2P_EFFECTIVE"

# ---- Emit coverage JSON for each lane --------------------------------
F2P_JSON_OK=true
P2P_JSON_OK=true
if [ -f "$COV_F2P_FILE" ]; then
    COVERAGE_FILE="$COV_F2P_FILE" "$PYTHON" -m coverage json --pretty-print \
        -o "$COV_F2P_JSON" 2>/tmp/cov-f2p.err || F2P_JSON_OK=false
else
    F2P_JSON_OK=false
fi
if [ -f "$COV_P2P_FILE" ]; then
    COVERAGE_FILE="$COV_P2P_FILE" "$PYTHON" -m coverage json --pretty-print \
        -o "$COV_P2P_JSON" 2>/tmp/cov-p2p.err || P2P_JSON_OK=false
else
    P2P_JSON_OK=false
fi

# ---- Compute final report --------------------------------------------
"$PYTHON" "$PRIV/compute_coverage.py" \
    --solution-patch "$PRIV/solution.patch" \
    --f2p-json "$COV_F2P_JSON" \
    --p2p-json "$COV_P2P_JSON" \
    --f2p-verdicts "$F2P_VERDICTS" \
    --p2p-verdicts "$P2P_VERDICTS" \
    --f2p-json-ok "$F2P_JSON_OK" \
    --p2p-json-ok "$P2P_JSON_OK" \
    --out "/out/coverage_report_${SUITE}.json"

# Mirror to the bundle root for the grader.
case "$SUITE" in
  orig) cp "/out/coverage_report_${SUITE}.json" /out/coverage_report.json ;;
  aug) : ;;
  union) : ;;
esac
cp "/out/coverage_report_${SUITE}.json" "$PRIV/coverage_report.json"

# Cross-check coverage_complete before exiting
"$PYTHON" -c "
import json, sys
r = json.load(open('/out/coverage_report_${SUITE}.json'))
sys.exit(0 if r.get('coverage_complete') else 2)
"
